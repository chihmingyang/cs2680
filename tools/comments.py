#!/usr/bin/env python3
"""站台留言（label comment 的 issue）的 session 端：列出等回答的、回覆並標成 answered。給 answer-comments skill 用。

James 在頁面上選一段文字按「留言」，docs/edit.js 開一個 issue：
  title  [l03] 留言的前 50 字
  body   <!-- cs2680:comment file=docs/l03.html anchor=i2-4 -->、頁面連結、> 引用的原文、留言
狀態：open 沒有 answered = 等 Claude；open 有 answered = 等 James 看；closed = James 按了「解決」。
James 在頁面上回覆會拿掉 answered，所以那一串會再出現在 list。

Usage:
  python3 -I tools/comments.py list              # 等 Claude 回答的留言，連同整串對話
  python3 -I tools/comments.py list --all        # 所有 open 的（含等 James 看的）
  python3 -I tools/comments.py reply <n> <file>  # 把 file 的 Markdown 貼成回覆（加上 Claude 標記），加 label answered

回覆用 Markdown（頁面只認：段落、- 清單、**粗**、`code`、[文字](https://…)、> 引用、```code```）。
"""
import json
import re
import subprocess
import sys
from pathlib import Path

REPO = "repos/chihmingyang/cs2680"
OWNER = "chihmingyang"
MARK = "<!-- cs2680:claude -->"


def api(path, *args, data=None):
    cmd = ["gh", "api", f"{REPO}{path}", *args]
    if data is not None:
        cmd += ["--input", "-"]
    out = subprocess.run(cmd, input=json.dumps(data) if data is not None else None,
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out) if out.strip() else None


def is_claude(c):
    return c["user"]["login"] != OWNER or MARK in (c.get("body") or "")


def strip(body):
    body = re.sub(r"<!--.*?-->\s*", "", body or "", flags=re.S)
    body = re.sub(r"\n-{3,}\s*\n_Generated by \[Claude Code\]\([^)]*\)_\s*$", "", body)   # 這個環境自動加的頁尾
    return re.sub(r"^頁面：\S+\s*", "", body).strip()


def labels(i):
    return {l["name"] for l in i["labels"]}


def cmd_list(show_all):
    issues = api("/issues?labels=comment&state=open&per_page=100&sort=created&direction=asc")
    issues = [i for i in issues if i["user"]["login"] == OWNER and "pull_request" not in i]
    if not show_all:
        issues = [i for i in issues if "answered" not in labels(i)]
    if not issues:
        print("沒有等回答的留言")
        return
    for i in issues:
        m = re.search(r"file=(\S+) anchor=([^\s>]*)", i["body"] or "")
        f, a = (m.group(1), m.group(2)) if m else ("?", "")
        state = "等 James 看" if "answered" in labels(i) else "等 Claude"
        print(f"\n===== #{i['number']}  {f}#{a}  （{state}，{i['created_at'][:10]}）")
        print(f"https://github.com/chihmingyang/cs2680/issues/{i['number']}")
        print("--- James：")
        print(strip(i["body"]))
        for c in api(f"/issues/{i['number']}/comments?per_page=100"):
            if c["user"]["login"] not in (OWNER, "github-actions[bot]"):
                continue                      # 公開 repo：別人的留言不進 prompt
            print("--- Claude：" if is_claude(c) else "--- James：")
            print(strip(c["body"]))
    print(f"\n共 {len(issues)} 串")


def cmd_reply(n, path):
    text = Path(path).read_text(encoding="utf-8").strip()
    api(f"/issues/{n}/comments", data={"body": MARK + "\n" + text})
    api(f"/issues/{n}/labels", data={"labels": ["answered"]})
    print(f"#{n} 已回覆，標成 answered")


def main():
    a = sys.argv[1:]
    if a[:1] == ["list"]:
        cmd_list("--all" in a)
    elif a[:1] == ["reply"] and len(a) == 3:
        cmd_reply(a[1], a[2])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
